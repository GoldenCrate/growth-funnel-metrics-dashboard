"""
Growth Funnel & Support-Deflection Metrics — Streamlit dashboard
================================================================

A multi-view business-operations dashboard built for the Decagon
"Business Operations, Growth" portfolio piece. It tells a build-measure-iterate
story across the full growth loop:

    1. Growth Overview   — headline KPI tiles + trend
    2. Funnel            — Visitor -> Signup -> Activated -> Paid, stage conversion
    3. Cohort Retention  — monthly cohort retention heatmap
    4. AI Support         — auto-resolution / deflection, CSAT, cost saved

ALL DATA IS SYNTHETIC (fixed seed, generated by data_gen.py). No real data.

Charting follows Cole Nussbaumer Knaflic's "Storytelling with Data":
takeaway titles that state the insight, decluttered axes, direct labels,
and a restrained palette where color is used only to carry meaning.

Run:
    pip install -r requirements.txt
    streamlit run app.py
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

import data_gen

# --------------------------------------------------------------------------------------
# Palette — restrained. One accent (teal) carries the "signal"; grey is context.
# --------------------------------------------------------------------------------------
ACCENT = "#1f948b"       # primary teal — the story color
ACCENT_DARK = "#14635c"
GREY = "#b7bcc2"         # context / de-emphasized
GREY_DARK = "#6b7177"
GOOD = "#1f948b"
WARN = "#d98c3f"
INK = "#2b2f33"          # text

st.set_page_config(
    page_title="Growth Funnel & Support-Deflection Metrics",
    page_icon="📈",
    layout="wide",
)


@st.cache_data
def load_data():
    return data_gen.generate_all()


DATA = load_data()
funnel = DATA["funnel"].copy()
cohorts = DATA["cohorts"].copy()
support = DATA["support"].copy()
revenue = DATA["revenue"].copy()


# --------------------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------------------
def pct(x: float) -> str:
    return f"{x:.1%}"


def money(x: float) -> str:
    return f"${x:,.0f}"


def clean_layout(fig: go.Figure, title: str, height: int = 420) -> go.Figure:
    """Apply Knaflic-style decluttering: takeaway title, no gridlines clutter,
    muted axes, legend only when needed."""
    fig.update_layout(
        title=dict(text=title, font=dict(size=18, color=INK), x=0.0, xanchor="left"),
        template="simple_white",
        height=height,
        margin=dict(l=10, r=20, t=70, b=40),
        font=dict(color=INK, size=13),
        plot_bgcolor="white",
        paper_bgcolor="white",
        hoverlabel=dict(bgcolor="white"),
    )
    fig.update_xaxes(showgrid=False, showline=True, linecolor=GREY, ticks="outside", tickcolor=GREY)
    fig.update_yaxes(showgrid=False, showline=False, zeroline=False)
    return fig


def so_what(text: str):
    st.markdown(
        f"""
        <div style="border-left:4px solid {ACCENT}; background:#f3f8f7;
                    padding:12px 16px; border-radius:4px; margin-top:8px;">
            <span style="font-weight:700; color:{ACCENT_DARK};">So what →</span>
            <span style="color:{INK};"> {text}</span>
        </div>
        """,
        unsafe_allow_html=True,
    )


def delta_pct(series: pd.Series) -> str:
    """Month-over-month change of the last value, as a formatted string for st.metric."""
    if len(series) < 2 or series.iloc[-2] == 0:
        return ""
    chg = series.iloc[-1] / series.iloc[-2] - 1
    return f"{chg:+.1%} MoM"


# --------------------------------------------------------------------------------------
# Sidebar
# --------------------------------------------------------------------------------------
st.sidebar.title("📈 Growth & Support Metrics")
st.sidebar.caption("Business Operations, Growth — portfolio demo")
view = st.sidebar.radio(
    "View",
    ["Growth Overview", "Funnel", "Cohort Retention", "AI Support Deflection"],
)
st.sidebar.markdown("---")
st.sidebar.warning(
    "**Synthetic data.** Every number here is generated from a fixed random "
    "seed by `data_gen.py`. No real company or customer data is used."
)
st.sidebar.markdown(
    "**Leo Chan** · [github.com/GoldenCrate](https://github.com/GoldenCrate)"
)


# =========================================================================
# VIEW 1 — GROWTH OVERVIEW
# =========================================================================
if view == "Growth Overview":
    st.title("Growth Overview")
    st.caption(
        "12-month view of the growth loop — acquisition, conversion, and revenue. "
        "All data synthetic."
    )

    latest = funnel.iloc[-1]
    first = funnel.iloc[0]
    activation_rate = latest["activated"] / latest["signups"]
    v2p = latest["paid"] / latest["visitors"]
    mrr_now = revenue["mrr_usd"].iloc[-1]

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Monthly signups", f"{int(latest['signups']):,}", delta_pct(funnel["signups"]))
    c2.metric("Activation rate", pct(activation_rate),
              f"{(activation_rate - first['activated']/first['signups'])*100:+.1f} pts vs. M1")
    c3.metric("Visitor→Paid conversion", pct(v2p),
              f"{(v2p - first['paid']/first['visitors'])*100:+.2f} pts vs. M1")
    c4.metric("MRR", money(mrr_now), delta_pct(revenue["mrr_usd"]))

    st.markdown("")

    # MRR trend — single accent line, direct end-label, no legend.
    mrr_growth = revenue["mrr_usd"].iloc[-1] / revenue["mrr_usd"].iloc[0] - 1
    fig = go.Figure()
    fig.add_trace(go.Scatter(
        x=revenue["month"], y=revenue["mrr_usd"],
        mode="lines+markers", line=dict(color=ACCENT, width=3),
        marker=dict(size=6, color=ACCENT), name="MRR",
        hovertemplate="%{x}<br>MRR: $%{y:,.0f}<extra></extra>",
    ))
    fig.add_annotation(
        x=revenue["month"].iloc[-1], y=revenue["mrr_usd"].iloc[-1],
        text=f"  {money(mrr_now)}", showarrow=False, xanchor="left",
        font=dict(color=ACCENT_DARK, size=14),
    )
    fig = clean_layout(
        fig,
        f"MRR grew {mrr_growth:.0%} over 12 months, to {money(mrr_now)}",
    )
    fig.update_yaxes(tickprefix="$", tickformat=",.0f")
    st.plotly_chart(fig, use_container_width=True)

    so_what(
        f"The loop is compounding: signups are up and activation improved to "
        f"{pct(activation_rate)}, pulling MRR to {money(mrr_now)}. The weakest link is "
        f"visitor→paid at just {pct(v2p)} — small lifts at the top of the funnel have "
        f"the largest absolute revenue impact, so acquisition-quality experiments should "
        f"be prioritized next quarter."
    )


# =========================================================================
# VIEW 2 — FUNNEL
# =========================================================================
elif view == "Funnel":
    st.title("Acquisition Funnel")
    st.caption("Visitor → Signup → Activated → Paid, latest 12-month totals. All data synthetic.")

    totals = {
        "Visitor": int(funnel["visitors"].sum()),
        "Signup": int(funnel["signups"].sum()),
        "Activated": int(funnel["activated"].sum()),
        "Paid": int(funnel["paid"].sum()),
    }
    stages = list(totals.keys())
    values = list(totals.values())

    # Stage-to-stage conversion rates.
    step_conv = [values[i + 1] / values[i] for i in range(len(values) - 1)]
    worst_idx = int(np.argmin(step_conv))
    worst_label = f"{stages[worst_idx]}→{stages[worst_idx+1]}"

    # Highlight the weakest conversion step in the accent color; others grey.
    bar_colors = [GREY] * len(values)
    bar_colors[worst_idx] = ACCENT
    bar_colors[worst_idx + 1] = ACCENT

    fig = go.Figure(go.Funnel(
        y=stages, x=values,
        textinfo="value+percent initial",
        marker=dict(color=bar_colors),
        connector=dict(line=dict(color=GREY, width=1)),
        hovertemplate="%{y}: %{x:,}<extra></extra>",
    ))
    fig = clean_layout(
        fig,
        f"Biggest drop-off is {worst_label} ({pct(step_conv[worst_idx])} convert)",
        height=440,
    )
    st.plotly_chart(fig, use_container_width=True)

    # Stage conversion table.
    st.subheader("Stage conversion rates")
    conv_df = pd.DataFrame({
        "Step": [f"{stages[i]} → {stages[i+1]}" for i in range(len(stages) - 1)],
        "Rate": [pct(c) for c in step_conv],
        "Drop-off": [f"{(1-c):.1%}" for c in step_conv],
    })
    st.dataframe(conv_df, hide_index=True, use_container_width=True)

    v2p_overall = values[-1] / values[0]
    so_what(
        f"Overall visitor→paid conversion is {pct(v2p_overall)}. The leakiest stage is "
        f"**{worst_label}** at {pct(step_conv[worst_idx])}. Because each stage multiplies, "
        f"fixing the weakest step compounds downstream — a 5-point lift there flows all the "
        f"way to paid. Recommend an A/B test targeting that transition before spending more "
        f"on top-of-funnel traffic."
    )


# =========================================================================
# VIEW 3 — COHORT RETENTION
# =========================================================================
elif view == "Cohort Retention":
    st.title("Cohort Retention")
    st.caption("Monthly signup cohorts, retention by months since signup. All data synthetic.")

    pivot = cohorts.pivot(index="cohort_month", columns="period_index", values="retention")
    pivot = pivot.sort_index()
    z = pivot.values * 100  # to percent
    text = np.where(np.isnan(z), "", np.vectorize(lambda v: f"{v:.0f}%")(np.nan_to_num(z)))

    # Sequential single-hue scale (white -> teal): intensity carries retention.
    colorscale = [[0.0, "#ffffff"], [0.5, "#9cc9c4"], [1.0, ACCENT_DARK]]

    fig = go.Figure(go.Heatmap(
        z=z,
        x=[f"M{c}" for c in pivot.columns],
        y=pivot.index,
        text=text,
        texttemplate="%{text}",
        textfont=dict(size=11),
        colorscale=colorscale,
        showscale=True,
        colorbar=dict(title="Retention", ticksuffix="%"),
        hovertemplate="Cohort %{y}<br>%{x}: %{z:.1f}%<extra></extra>",
        zmin=0, zmax=100,
    ))

    # Month-1 retention trend across cohorts for the takeaway.
    m1 = pivot[1].dropna()
    m1_trend = m1.iloc[-1] - m1.iloc[0]
    fig = clean_layout(
        fig,
        f"Month-1 retention improved {m1_trend*100:+.0f} pts across newer cohorts",
        height=520,
    )
    fig.update_yaxes(showline=False, autorange="reversed")
    fig.update_xaxes(side="top")
    st.plotly_chart(fig, use_container_width=True)

    floor = pivot.min().min()
    so_what(
        f"Retention follows the classic decay-then-flatten shape, stabilizing around a "
        f"loyal core (floor ≈ {pct(floor)}). Newer cohorts retain better at Month-1 "
        f"(+{m1_trend*100:.0f} pts), evidence that onboarding/activation changes are "
        f"working. The leverage point is the Month-0→Month-1 cliff: tightening the first-week "
        f"activation experience is the highest-ROI retention investment."
    )


# =========================================================================
# VIEW 4 — AI SUPPORT DEFLECTION
# =========================================================================
elif view == "AI Support Deflection":
    st.title("AI Support Deflection")
    st.caption(
        "AI auto-resolution vs. human escalation, CSAT, and cost saved. All data synthetic."
    )

    s_latest = support.iloc[-1]
    s_first = support.iloc[0]
    total_saved = support["cost_saved_usd"].sum()
    total_deflected = int(support["deflected"].sum())

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Auto-resolution rate", pct(s_latest["deflection_rate"]),
              f"{(s_latest['deflection_rate']-s_first['deflection_rate'])*100:+.0f} pts vs. M1")
    c2.metric("CSAT (AI-handled)", f"{s_latest['csat']:.2f} / 5",
              f"{s_latest['csat']-s_first['csat']:+.2f} vs. M1")
    c3.metric("Tickets deflected (12mo)", f"{total_deflected:,}")
    c4.metric("Cost saved (12mo)", money(total_saved))

    st.markdown("")

    # Stacked bar: deflected (accent) vs escalated (grey). Deflection line could clutter;
    # keep it to two bars + a takeaway title.
    fig = go.Figure()
    fig.add_trace(go.Bar(
        x=support["month"], y=support["deflected"], name="AI auto-resolved",
        marker_color=ACCENT,
        hovertemplate="%{x}<br>Auto-resolved: %{y:,}<extra></extra>",
    ))
    fig.add_trace(go.Bar(
        x=support["month"], y=support["escalated"], name="Escalated to human",
        marker_color=GREY,
        hovertemplate="%{x}<br>Escalated: %{y:,}<extra></extra>",
    ))
    fig.update_layout(barmode="stack", legend=dict(
        orientation="h", yanchor="bottom", y=1.02, xanchor="left", x=0))
    fig = clean_layout(
        fig,
        f"AI now resolves {pct(s_latest['deflection_rate'])} of tickets without a human",
        height=430,
    )
    fig.update_yaxes(tickformat=",.0f", title_text="Tickets / month")
    st.plotly_chart(fig, use_container_width=True)

    # Cost saved cumulative.
    col_a, col_b = st.columns(2)
    with col_a:
        cum = support["cost_saved_usd"].cumsum()
        fig2 = go.Figure(go.Scatter(
            x=support["month"], y=cum, mode="lines", fill="tozeroy",
            line=dict(color=ACCENT, width=2.5), fillcolor="rgba(31,148,139,0.12)",
            hovertemplate="%{x}<br>Cumulative saved: $%{y:,.0f}<extra></extra>",
        ))
        fig2 = clean_layout(fig2, f"Cumulative cost saved: {money(cum.iloc[-1])}", height=340)
        fig2.update_yaxes(tickprefix="$", tickformat=",.0f")
        st.plotly_chart(fig2, use_container_width=True)
    with col_b:
        fig3 = go.Figure(go.Scatter(
            x=support["month"], y=support["csat"], mode="lines+markers",
            line=dict(color=ACCENT_DARK, width=2.5), marker=dict(size=5),
            hovertemplate="%{x}<br>CSAT: %{y:.2f}<extra></extra>",
        ))
        fig3 = clean_layout(fig3, "CSAT held high while deflection rose", height=340)
        fig3.update_yaxes(range=[3.5, 5.0], title_text="CSAT (1–5)")
        st.plotly_chart(fig3, use_container_width=True)

    so_what(
        f"Deflection climbed to {pct(s_latest['deflection_rate'])} while CSAT stayed at "
        f"{s_latest['csat']:.2f}/5 — the AI is deflecting *more* volume without hurting "
        f"experience, which is the key guardrail. That is {total_deflected:,} tickets kept off "
        f"human queues and {money(total_saved)} saved this year. Next: segment the ~"
        f"{pct(1-s_latest['deflection_rate'])} that still escalate to find the top intents to "
        f"automate — that backlog is the clearest path to the next margin step-change."
    )

